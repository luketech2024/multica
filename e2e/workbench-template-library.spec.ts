import { test, expect } from "@playwright/test";
import { createTestApi, loginAsDefault } from "./helpers";
import type { TestApiClient } from "./fixtures";

test.describe("Workspace template versions", () => {
  test.use({ locale: "en-US" });
  let api: TestApiClient;
  test.afterEach(async () => { await api?.cleanup(); });
  test("publishes a shared version, selectively merges it and offers saved copies to new projects", async ({ page }) => {
    test.setTimeout(120000);
    api = await createTestApi();
    const asset = await api.createBusinessTemplate({ v: 1, name: "Template acceptance v1", background: [], audience: [], scope_out: ["Keep project scope"], ac_skeleton: [], forbidden: [], dod: ["Initial check"], resources: [], terms: {} });
    const project = await api.createProject("Template version acceptance", { description: "Retain project customizations", business_template: { id: asset.id, revision: 1 } });
    const slug = await loginAsDefault(page);
    const errors: string[] = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto(`/${slug}/projects/${project.id}`);
    await page.getByRole("button", { name: "Edit workspace template", exact: true }).click();
    let dialog = page.getByRole("dialog");
    await dialog.getByRole("textbox", { name: "Template name", exact: true }).fill("Template acceptance v2");
    await dialog.getByRole("textbox", { name: "Definition of done", exact: true }).fill("Updated validation check");
    await dialog.getByRole("button", { name: "Save", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    await page.getByRole("button", { name: "Review template v2", exact: true }).click();
    dialog = page.getByRole("dialog");
    await expect(dialog.getByText("Template acceptance v1", { exact: true })).toBeVisible();
    await expect(dialog.getByText("Template acceptance v2", { exact: true })).toBeVisible();
    await dialog.getByRole("checkbox", { name: "Definition of done", exact: true }).check();
    await page.screenshot({ path: ".preview/workbench-template-merge.png", fullPage: true });
    await dialog.getByRole("button", { name: "Merge selected fields", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    await page.reload();
    await expect(page.getByRole("button", { name: "Review template v2", exact: true })).toHaveCount(0);
    await page.getByText("Template acceptance v1", { exact: true }).click();
    await expect(page.getByText("Updated validation check", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Save as workspace template", exact: true }).click();
    dialog = page.getByRole("dialog");
    await dialog.getByRole("textbox", { name: "Template name", exact: true }).fill("Template acceptance copy");
    const savedResponse = page.waitForResponse((response) => response.request().method() === "POST" && response.url().endsWith("/api/workbench/business-templates"));
    await dialog.getByRole("button", { name: "Save", exact: true }).click();
    const saved = await (await savedResponse).json();
    api.trackBusinessTemplate(saved.id);
    await expect(dialog).not.toBeVisible();
    await page.goto(`/${slug}/projects`);
    await page.getByRole("button", { name: "New project", exact: true }).first().click();
    await expect(page.getByRole("dialog").getByRole("button", { name: /Template acceptance copy/ })).toBeVisible();
    await page.keyboard.press("Escape");
    expect(errors).toEqual([]);
  });
});
