import "./env";
import { test, expect } from "@playwright/test";
import { createHash, randomBytes } from "node:crypto";
import pg from "pg";
import { createTestApi } from "./helpers";

test("asynchronous choices, readable PRD and prototype share one confirmed version", async ({ page }, testInfo) => {
  test.setTimeout(120_000);
  const api = await createTestApi();
  const db = new pg.Client(process.env.DATABASE_URL);
  await db.connect();
  let runtimeId: string | undefined;
  let agentId: string | undefined;
  try {
    const workspace = (await api.getWorkspaces())[0]!;
    const user = (await db.query(`SELECT id FROM "user" WHERE email=$1`, [api.getEmail()])).rows[0].id;
    runtimeId = (await db.query(`INSERT INTO agent_runtime(workspace_id,name,runtime_mode,provider,status,device_info,metadata,owner_id,last_seen_at) VALUES($1,'PRD test','cloud','cursor','online','E2E','{}',$2,now()) RETURNING id`, [workspace.id, user])).rows[0].id;
    agentId = (await db.query(`INSERT INTO agent(workspace_id,name,description,instructions,runtime_mode,runtime_config,runtime_id,visibility,permission_mode,max_concurrent_tasks,owner_id) VALUES($1,'Product test','','','cloud','{}',$2,'private','private',1,$3) RETURNING id`, [workspace.id, runtimeId, user])).rows[0].id;
    const project = await api.createProject("Readable requirements review");
    const repo = await api.createProjectRepository(project.id, "https://example.test/prd.git");
    const memberHeaders = { Authorization: `Bearer ${api.getToken()}`, "Content-Type": "application/json", "X-Workspace-ID": workspace.id };
    const rolesURL = `${process.env.NEXT_PUBLIC_API_URL}/api/projects/${project.id}/workbench-roles`;
    const roles = await (await fetch(rolesURL, { headers: memberHeaders })).json();
    roles.config.roles.product = { enabled: true, agent_id: agentId, runtime_id: runtimeId };
    roles.config.roles.dev = { enabled: true, agent_id: agentId, runtime_id: runtimeId };
    const savedRoles = await fetch(rolesURL, { method: "PUT", headers: memberHeaders, body: JSON.stringify({ expected_revision: roles.revision, config: roles.config }) });
    expect(savedRoles.status, await savedRoles.text()).toBe(200);
    await api.configureOneSpec(project.id, { enabled: true, runtime_id: runtimeId, overview_repository_id: repo.id, expected_revision: 0 });
    const issue = await api.createIssue("Discuss a homepage", { project_id: project.id });
    await db.query(`UPDATE issue SET assignee_type='agent',assignee_id=$2 WHERE id=$1`, [issue.id, agentId]);
    const task = (await db.query(`INSERT INTO agent_task_queue(agent_id,runtime_id,issue_id,status,started_at) VALUES($1,$2,$3,'running',now()) RETURNING id`, [agentId, runtimeId, issue.id])).rows[0].id;
    const token = `mat_${randomBytes(20).toString("hex")}`;
    await db.query(`INSERT INTO task_token(token_hash,task_id,agent_id,workspace_id,user_id,expires_at) VALUES($1,$2,$3,$4,$5,now()+interval '1 hour')`, [createHash("sha256").update(token).digest("hex"), task, agentId, workspace.id, user]);
    const agentHeaders = { Authorization: `Bearer ${token}`, "Content-Type": "application/json", "X-Workspace-ID": workspace.id };
    const request = { origin: "platform", key: "environment", questions: [{ id: "env", header: "Environment", question: "When should we select a server?", isOther: true, options: [{ label: "Before deployment", description: "Discuss requirements first", recommended: true }] }] };
    const asked = await fetch(`${process.env.NEXT_PUBLIC_API_URL}/api/issues/${issue.id}/input-requests`, { method: "POST", headers: agentHeaders, body: JSON.stringify(request) });
    expect(asked.status, await asked.text()).toBe(200);
    await db.query(`UPDATE agent_task_queue SET status='completed',completed_at=now() WHERE id=$1`, [task]);
    await page.addInitScript((token) => localStorage.setItem("multica_token", token!), api.getToken());
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(`/${workspace.slug}/issues/${issue.id}`);
    const composer = page.getByTestId("user-input-composer");
    await expect(composer).toBeVisible();
    await expect(composer.getByText("Discuss requirements first")).toBeVisible();
    await composer.getByRole("button", { name: /Before deployment/ }).click();
    await expect(composer.getByRole("button", { name: /Before deployment/ })).toHaveAttribute("aria-pressed", "true");
    await page.reload();
    await expect(composer.getByRole("textbox", { name: "Answer", exact: true })).toHaveText("Before deployment");
    await composer.getByRole("button", { name: "Submit answers", exact: true }).click();
    await expect(composer).toHaveCount(0);
    await api.prepareRequirementsReview(issue.id);
    const content = "# Homepage requirements\n\n## Scope\nA static homepage with a contact button.\n\n## Acceptance\nClick Contact to show contact information.";
    const html = '<!doctype html><html><body><h1>Homepage sample</h1><button onclick="document.getElementById(\'result\').textContent=\'Contact shown\'">Contact</button><p id="result"></p></body></html>';
    const file = (path: string, text: string) => ({ content: text, verified: false, ref: { repository_id: repo.id, path, commit: "a".repeat(40), digest: createHash("sha256").update(text).digest("hex") } });
    const document = { ...file("onespec/changes/task/prd.md", content), prototype_status: "ready", prototype: file("onespec/changes/task/prototype.html", html) };
    const state = await api.oneSpec(issue.id);
    await db.query(`UPDATE agent_task_queue SET status='running' WHERE id=$1`, [task]);
    const published = await fetch(`${process.env.NEXT_PUBLIC_API_URL}/api/issues/${issue.id}/onespec/artifact`, { method: "POST", headers: agentHeaders, body: JSON.stringify({ expected_revision: state.revision, artifact: { stage: "requirements", summary: "Homepage and contact interaction", refs: [document.ref, document.prototype.ref], document } }) });
    expect(published.status, await published.text()).toBe(200);
    await page.reload();
    const summary = page.getByTestId("requirements-summary").first();
    await expect(summary.getByRole("heading", { name: "Homepage requirements", exact: true })).toBeHidden();
    await summary.getByText("Read requirements", { exact: true }).click();
    await expect(summary.getByRole("heading", { name: "Homepage requirements", exact: true })).toBeVisible();
    await expect(summary.getByText("Verifying committed files").first()).toBeVisible();
    await expect(summary.getByRole("checkbox")).toHaveCount(0);
    const frame = page.frameLocator('[data-testid="requirements-prototype"] iframe');
    await page.getByTestId("requirements-prototype").locator("summary").click();
    await frame.getByRole("button", { name: "Contact", exact: true }).click();
    await expect(frame.getByText("Contact shown")).toBeVisible();
    await summary.getByRole("button", { name: "Quote A-01", exact: true }).click();
    await expect(page.getByRole("textbox", { name: "Comment or instruction for this task", exact: true })).toContainText("A-01");
    // The daemon callback is simulated here; committed-file verification has its own Git fixture test.
    await db.query(`UPDATE agent_task_queue SET status='running' WHERE id=$1`, [task]);
    const verified = await fetch(`${process.env.NEXT_PUBLIC_API_URL}/api/daemon/tasks/${task}/requirements-document`, { method: "POST", headers: { Authorization: `Bearer ${api.getToken()}`, "Content-Type": "application/json", "X-Workspace-ID": workspace.id }, body: JSON.stringify({ version: 1, error: "", prototype_error: "" }) });
    expect(verified.status).toBe(200);
    await db.query(`UPDATE agent_task_queue SET status='completed',completed_at=now() WHERE issue_id=$1`, [issue.id]);
    await page.reload();
    await expect(summary.getByRole("checkbox")).toBeVisible();
    await page.setViewportSize({ width: 390, height: 844 });
    await summary.getByRole("checkbox").scrollIntoViewIfNeeded();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath("requirements-review-narrow.png") });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: testInfo.outputPath("requirements-review.png") });
    await summary.getByRole("checkbox").click();
    await expect(summary.getByRole("checkbox")).toBeChecked();
    await expect(summary.getByRole("checkbox")).toBeEnabled();
    await summary.getByRole("checkbox").click();
    await expect(summary.getByRole("checkbox")).not.toBeChecked();
    await expect(summary.getByRole("checkbox")).toBeEnabled();
    await summary.getByRole("checkbox").click();
    const confirm = summary.getByRole("button", { name: "Confirm requirements and start Design", exact: true });
    await expect(confirm).toBeDisabled();
    await expect(summary.getByText(/Your requirement change is still a draft/)).toBeVisible();
    await summary.getByRole("button", { name: "Keep draft for later", exact: true }).click();
    // Simulate a startup outage after confirmation and advancement have persisted.
    await page.route(`**/api/issues/${issue.id}/onespec/run`, async (route) => {
      await route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: "Stage startup temporarily unavailable" }) });
    }, { times: 1 });
    await confirm.click();
    await expect.poll(async () => (await api.getIssue(issue.id)).acceptance_criteria.gate.spec).toBeTruthy();
    const handoff = page.getByTestId("requirements-handoff");
    await expect(handoff).toContainText("Design has not started");
    expect((await api.oneSpec(issue.id)).flow.phase).toBe("design");
    await expect(page.getByText("Platform rule version", { exact: false })).toHaveCount(0);
    await handoff.getByRole("button", { name: "Start Design", exact: true }).click();
    await expect.poll(async () => (await db.query(`SELECT count(*)::int AS n FROM agent_task_queue WHERE issue_id=$1 AND status IN ('queued','dispatched','running')`, [issue.id])).rows[0].n).toBe(1);
    await expect(handoff.getByRole("button", { name: "Start Design", exact: true })).toHaveCount(0);
    await expect(handoff).toContainText("Design is queued");
    await expect(page.getByRole("textbox", { name: "Comment or instruction for this task", exact: true })).toContainText("A-01");
    const started = await api.oneSpec(issue.id);
    const retry = await fetch(`${process.env.NEXT_PUBLIC_API_URL}/api/issues/${issue.id}/onespec/run`, { method: "POST", headers: memberHeaders, body: JSON.stringify({ expected_revision: started.revision }) });
    expect(retry.status, await retry.text()).toBe(200);
    expect((await db.query(`SELECT count(*)::int AS n FROM agent_task_queue WHERE issue_id=$1 AND status IN ('queued','dispatched','running')`, [issue.id])).rows[0].n).toBe(1);
    await page.screenshot({ path: testInfo.outputPath("requirements-confirmed.png") });
    await db.query(`UPDATE agent_task_queue SET status='completed',completed_at=now() WHERE issue_id=$1`, [issue.id]);
    await page.reload();
    await expect(handoff).toContainText("Design has not produced a reviewable result yet");
  } finally {
    await api.cleanup();
    if (agentId) await db.query(`DELETE FROM task_token WHERE agent_id=$1`, [agentId]);
    if (agentId) await db.query(`DELETE FROM agent_task_queue WHERE agent_id=$1`, [agentId]);
    if (agentId) await db.query(`DELETE FROM agent WHERE id=$1`, [agentId]);
    if (runtimeId) await db.query(`DELETE FROM agent_runtime WHERE id=$1`, [runtimeId]);
    await db.end();
  }
});
