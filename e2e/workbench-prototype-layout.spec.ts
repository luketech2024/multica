import { test, expect } from '@playwright/test';
import { createTestApi, loginAsDefault } from './helpers';
import type { TestApiClient } from './fixtures';

test.use({ locale: 'en-US', viewport: { width: 1440, height: 900 } });
let api: TestApiClient;
test.afterEach(async () => { await api?.cleanup(); });
test('prototype layout retains confirmation when the right pane becomes a drawer', async ({ page }) => {
  test.setTimeout(180000);
  api = await createTestApi();
  const project = await api.createProject('Visual alignment check');
  const task = await api.createIssue('Confirm report fields', { project_id: project.id, acceptance_criteria: { v: 1, items: [{ id: '', text: 'Include account and amount' }], bounds: ['Exclude payment integration'] } });
  const slug = await loginAsDefault(page);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`/${slug}/projects`);
  await expect(page.getByRole('article').filter({ hasText: project.title })).toBeVisible();
  await page.goto(`/${slug}/issues/${task.id}`);
  const field = page.getByRole('checkbox', { name: 'Check A-01', exact: true });
  await expect(field).toBeVisible();
  await field.click();
  await expect(field).toBeChecked();
  const confirm = page.getByRole('button', { name: 'Confirm requirements', exact: true });
  await expect(confirm).toBeEnabled();
  await page.setViewportSize({ width: 1280, height: 900 });
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(confirm).toBeVisible();
  await page.getByRole('button', { name: 'Toggle right sidebar', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(field).toBeChecked();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toBeHidden();
  await confirm.click();
  await expect(page.getByText('Requirements confirmed and locked', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Requirements confirmed and locked', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 1024, height: 720 });
  await expect(page.locator('nav[data-slot="app-rail"]')).toHaveAttribute('data-expanded', 'false');
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
