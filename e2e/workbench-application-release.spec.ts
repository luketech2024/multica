import { test, expect } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { generateKeyPairSync } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createTestApi, loginAsDefault } from "./helpers";
import type { TestApiClient } from "./fixtures";

test.describe("Application release workflow", () => {
  test.use({ locale: "en-US" });
  let api: TestApiClient;
  test.afterEach(async () => { await api?.cleanup(); });

  test("saves password login only after confirming the detected server identity", async ({page})=>{
    api = await createTestApi();
    const project = await api.createProject("Password deployment");
    api.trackApplicationReleaseProject(project.id);
    const slug = await loginAsDefault(page);
    const fingerprint = "SHA256:" + "A".repeat(43);
    let candidate = fingerprint;
    await page.route("**/deployment/discover-host",route=>route.fulfill({status:200,contentType:"application/json",body:JSON.stringify({host_key:candidate})}));
    await page.goto(`/${slug}/projects/${project.id}?tab=deployment`);
    await page.getByRole("button",{name:"Add server",exact:true}).click();
    const dialog = page.getByRole("dialog");
    await dialog.getByRole("combobox",{name:"Login method",exact:true}).click();
    await page.getByRole("option",{name:"Password login",exact:true}).click();
    await dialog.getByRole("textbox",{name:"Name",exact:true}).fill("Root password server");
    await dialog.getByRole("textbox",{name:"Server address",exact:true}).fill("192.0.2.22");
    await dialog.getByRole("textbox",{name:"SSH user",exact:true}).fill("root");
    await dialog.getByRole("button",{name:"Add SSH credential",exact:true}).click();
    await expect(dialog.getByLabel("Upload private key file")).toHaveCount(0);
    const password = dialog.getByLabel("Login password",{exact:true});
    await expect(password).toHaveAttribute("type","password");
    await password.fill("synthetic-password-for-test");
    await dialog.getByRole("button",{name:"Save and select credential",exact:true}).click();
    await expect(password).toHaveCount(0);
    await expect(dialog.getByRole("button",{name:"Save",exact:true})).toBeDisabled();
    await dialog.getByRole("button",{name:"Detect server identity",exact:true}).click();
    await expect(dialog.getByText(fingerprint,{exact:true})).toBeVisible();
    await expect(dialog.getByRole("button",{name:"Save",exact:true})).toBeDisabled();
    await dialog.getByRole("button",{name:"Confirm server identity",exact:true}).click();
    const connectionCheck = dialog.getByRole("button", {name:"Check SSH connection",exact:true});
    let checkOK = false;
    await page.route("**/deployment/check-resource", async route => {
      const request = route.request().postDataJSON();
      expect(request.auth_method).toBe("password");
      expect(request.host_key).toBe(fingerprint);
      expect(request.credential_id).toBeTruthy();
      await route.fulfill({status:200,contentType:"application/json",body:JSON.stringify({ok:checkOK,detail:checkOK ? "" : "SSH server is unreachable"})});
    });
    await connectionCheck.click();
    await expect(dialog.getByRole("status").filter({hasText:"SSH server is unreachable"})).toBeVisible();
    checkOK = true;
    await connectionCheck.click();
    await expect(dialog.getByText("SSH connection verified",{exact:true})).toBeVisible();
    await dialog.getByRole("textbox",{name:"SSH user",exact:true}).fill("deploy");
    await expect(dialog.getByText("SSH connection verified",{exact:true})).toHaveCount(0);
    await dialog.getByRole("textbox",{name:"SSH user",exact:true}).fill("root");
    const saved = page.waitForResponse(response=>response.url().endsWith(`/projects/${project.id}/deployment`)&&response.request().method()==="PUT");
    await dialog.getByRole("button",{name:"Save",exact:true}).click();
    const config = await (await saved).json();
    expect(config.config.resources[0]).toMatchObject({auth_method:"password",username:"root",host_key:fingerprint});
    expect(JSON.stringify(config)).not.toContain("synthetic-password-for-test");
    await expect(dialog).not.toBeVisible();
    await page.reload();
    await page.getByRole("button",{name:"Edit resource",exact:true}).click();
    await expect(dialog.getByRole("combobox",{name:"Login method",exact:true})).toContainText("Password login");
    candidate="SHA256:"+"B".repeat(43);
    await dialog.getByRole("button",{name:"Detect server identity",exact:true}).click();
    await expect(dialog.getByRole("alert")).toContainText("fingerprint changed");
    await expect(dialog.getByText(`Confirmed fingerprint · ${fingerprint}`,{exact:true})).toBeVisible();
    await dialog.getByRole("textbox",{name:"Server address",exact:true}).fill("192.0.2.23");
    await expect(dialog.getByRole("button",{name:"Confirm server identity",exact:true})).toHaveCount(0);
    await expect(dialog.getByRole("button",{name:"Save",exact:true})).toBeDisabled();
  });

  test("creates an SSH credential while adding a server and preserves input after a failed save", async ({ page }) => {
    api = await createTestApi();
    const project = await api.createProject("Inline SSH credential");
    api.trackApplicationReleaseProject(project.id);
    const slug = await loginAsDefault(page);
    await page.goto(`/${slug}/projects/${project.id}?tab=deployment`);
    await page.getByRole("button", {name:"Add server",exact:true}).click();
    const dialog = page.getByRole("dialog");
    await dialog.getByRole("textbox",{name:"Name",exact:true}).fill("Inline server");
    await dialog.getByRole("textbox",{name:"Server address",exact:true}).fill("192.0.2.21");
    await dialog.getByText("Enter fingerprint manually", {exact:true}).click();
    await dialog.getByRole("textbox",{name:"SSH host fingerprint (SHA256)"}).fill("SHA256:AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA");
    await expect(dialog.getByText("ssh-keygen -lf /etc/ssh/ssh_host_ed25519_key.pub -E sha256",{exact:true})).toBeVisible();
    await dialog.getByRole("button",{name:"Add SSH credential",exact:true}).click();
    await expect(dialog.getByRole("textbox",{name:"Credential name",exact:true})).toHaveValue("Inline server");
    await dialog.getByLabel("Upload private key file").setInputFiles({name:"too-large.key",mimeType:"text/plain",buffer:Buffer.alloc(65537)});
    await expect(dialog.getByRole("alert")).toContainText("64 KiB");
    const {privateKey} = generateKeyPairSync("ed25519",{privateKeyEncoding:{type:"pkcs8",format:"pem"},publicKeyEncoding:{type:"spki",format:"pem"}});
    await dialog.getByLabel("Upload private key file").setInputFiles({name:"deploy.key",mimeType:"text/plain",buffer:Buffer.from(privateKey)});
    await expect(dialog.getByRole("textbox",{name:"SSH private key",exact:true})).toHaveValue(privateKey);
    await page.route("**/api/workbench/credentials",async route=>{
      if(route.request().method()==="POST") await route.fulfill({status:503,contentType:"application/json",body:JSON.stringify({error:"Credential save temporarily unavailable"})});
      else await route.continue();
    });
    await dialog.getByRole("button",{name:"Save and select credential",exact:true}).click();
    await expect(dialog.getByRole("alert")).toContainText("Credential save temporarily unavailable");
    await expect(dialog.getByRole("textbox",{name:"SSH private key",exact:true})).toHaveValue(privateKey);
    await expect(dialog.getByRole("textbox",{name:"Server address",exact:true})).toHaveValue("192.0.2.21");
    await page.unroute("**/api/workbench/credentials");
    await dialog.getByRole("button",{name:"Save and select credential",exact:true}).click();
    await expect(dialog.getByRole("combobox",{name:"SSH credential",exact:true})).toContainText("Inline server");
    await expect(dialog.getByRole("textbox",{name:"SSH private key",exact:true})).toHaveCount(0);
    await dialog.getByRole("button",{name:"Save",exact:true}).click();
    await expect(dialog).not.toBeVisible();
    await page.reload();
    await page.getByRole("button",{name:"Edit resource",exact:true}).click();
    await expect(dialog.getByRole("combobox",{name:"SSH credential",exact:true})).toContainText("Inline server");
    await expect(dialog.getByRole("textbox",{name:"Server address",exact:true})).toHaveValue("192.0.2.21");
  });

  test("saves existing applications, uploads a real certificate and returns to the release draft", async ({ page }) => {
    test.setTimeout(180000);
    api = await createTestApi();
    const project = await api.createProject("Application release review");
    api.trackApplicationReleaseProject(project.id);
    const credential = await api.createDeploymentCredential(project.id, "ssh-key", "fixture-key-not-used-for-execution");
    const slug = await loginAsDefault(page);
    const errors: string[] = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.goto(`/${slug}/projects/${project.id}?tab=applications`);
    await page.getByRole("button", { name: "Add application", exact: true }).click();
    const dialog = page.getByRole("dialog");
    await dialog.getByRole("textbox", { name: "Name", exact: true }).fill("Website");
    await dialog.getByRole("textbox", { name: "Repository, image or server path" }).fill("https://example.test/website.git");
    await dialog.getByRole("textbox", { name: "Artifact directory relative to source" }).fill("dist");
    await dialog.getByRole("button", { name: "Save", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    await page.getByRole("link", { name: "New release", exact: true }).click();
    await page.getByRole("button", { name: "Publish existing applications", exact: true }).click();
    await dialog.getByRole("textbox", { name: "Release name" }).fill("Website v1.0.1");
    await dialog.getByRole("button", { name: "New release", exact: true }).click();
    await expect(page.getByRole("textbox", { name: "Target version" })).toBeVisible();
    await page.getByRole("textbox", { name: "Target version" }).fill("v1.0.1");
    await page.getByRole("button", { name: "Configure deployment", exact: true }).click();
    await dialog.getByRole("button", { name: "Next", exact: true }).click();
    await dialog.getByRole("button", { name: "Add server", exact: true }).click();
    await dialog.getByRole("textbox", { name: "Name", exact: true }).fill("Website server");
    await dialog.getByRole("textbox", { name: "Server address", exact: true }).fill("192.0.2.20");
    await dialog.getByText("Enter fingerprint manually", {exact:true}).click();
    await dialog.getByRole("textbox", { name: "SSH host fingerprint (SHA256)" }).fill("SHA256:AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA");
    await dialog.getByRole("combobox", { name: "SSH credential", exact: true }).click();
    await page.getByRole("option", { name: credential.label, exact: true }).click();
    await dialog.getByRole("button", { name: "Save", exact: true }).click();
    await expect(dialog.getByRole("checkbox", { name: "Website server 192.0.2.20" })).toBeChecked();
    await dialog.getByRole("button", { name: "Next", exact: true }).click();
    await dialog.getByRole("textbox", { name: "Domain", exact: true }).fill("www.example.test");
    await dialog.getByText("Advanced settings", {exact:true}).click();
    await dialog.getByRole("textbox", {name:"Nginx configuration directory",exact:true}).fill("/etc/nginx/conf.d/config");
    await dialog.getByRole("combobox", { name: "HTTPS", exact: true }).click();
    await page.getByRole("option", { name: "Use existing certificate", exact: true }).click();
    await dialog.getByRole("button", { name: "Upload certificate", exact: true }).click();
    await dialog.getByRole("textbox", { name: "Certificate name", exact: true }).fill("Website certificate");
    await dialog.getByLabel("Certificate chain (.pem)").setInputFiles({ name: "fullchain.pem", mimeType: "text/plain", buffer: Buffer.from("invalid certificate") });
    await dialog.getByLabel("Private key (.key)").setInputFiles({ name: "private.key", mimeType: "text/plain", buffer: Buffer.from("invalid key") });
    await dialog.getByRole("button", { name: "Validate and save", exact: true }).click();
    await expect(dialog.getByRole("alert")).toContainText("valid matching pair");
    const directory = mkdtempSync(join(tmpdir(), "multica-cert-test-"));
    try {
      const cert = join(directory, "fullchain.pem");
      const key = join(directory, "private.key");
      execFileSync("openssl", ["req", "-x509", "-newkey", "rsa:2048", "-nodes", "-keyout", key, "-out", cert, "-days", "2", "-subj", "/CN=www.example.test", "-addext", "subjectAltName=DNS:www.example.test"], { stdio: "ignore" });
      await dialog.getByLabel("Certificate chain (.pem)").setInputFiles({ name: "fullchain.pem", mimeType: "text/plain", buffer: readFileSync(cert) });
      await dialog.getByLabel("Private key (.key)").setInputFiles({ name: "private.key", mimeType: "text/plain", buffer: readFileSync(key) });
      await dialog.getByRole("button", { name: "Validate and save", exact: true }).click();
    } finally { rmSync(directory, { recursive: true, force: true }); }
    await expect(dialog.getByRole("combobox", { name: "Certificate resource" })).toContainText("Website certificate");
    await page.screenshot({ path: ".preview/application-certificate.png", fullPage: true });
    await dialog.getByRole("button", { name: "Next", exact: true }).click();
    await dialog.getByRole("button", { name: "Save and return", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    const deploymentResponse = await api.authedFetch(`/api/projects/${project.id}/deployment`);
    const deploymentData = await deploymentResponse.json();
    expect(deploymentData.config.applications[0].environments.staging.nginx_config_directory).toBe("/etc/nginx/conf.d/config");
    await expect(page.getByRole("textbox", { name: "Target version" })).toHaveValue("v1.0.1");
    await page.getByRole("combobox", { name: "Upgrade mode", exact: true }).click();
    await page.getByRole("option", { name: "Release orchestrates changes", exact: true }).click();
    await page.getByRole("button", { name: "Add SQL", exact: true }).click();
    await page.getByRole("textbox", { name: "Target version" }).last().fill("migration-1");
    await page.getByRole("textbox", { name: "Database connection on server" }).fill("production");
    await page.getByRole("textbox", { name: "Change content" }).fill("SELECT 1;");
    await page.getByRole("checkbox", { name: "I reviewed the SQL rehearsal result" }).check();
    await page.getByRole("button", { name: "Next", exact: true }).click();
    await expect(page.getByRole("combobox", { name: "Depends on" })).toHaveCount(2);
    await page.getByRole("button", { name: "Next", exact: true }).click();
    await expect(page.getByRole("button", { name: "Start release", exact: true })).toBeDisabled();
    await page.getByRole("checkbox", { name: "I have reviewed the change list" }).check();
    await page.getByRole("checkbox", { name: "I have confirmed database migrations or verified that none are required" }).check();
    await page.getByRole("button", { name: "Save confirmations", exact: true }).click();
    await expect(page.getByRole("button", { name: "Start release", exact: true })).toBeEnabled();
    await page.screenshot({ path: ".preview/application-release-review.png", fullPage: true });
    await page.reload();
    await expect(page.getByRole("textbox", { name: "Target version" }).first()).toHaveValue("v1.0.1");
    await expect(page.getByRole("textbox", { name: "Change content" })).toHaveValue("SELECT 1;");
    await page.goto(`/${slug}/projects/${project.id}?tab=deployment`);
    await expect(page.getByRole("heading", { name: "Environment resources", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Check SSH connection", exact: true }).click();
    await expect(page.getByText("SSH private key cannot be read", {exact: true})).toBeVisible();
    await page.getByRole("button", { name: "Edit resource", exact: true }).click();
    await dialog.getByRole("textbox", {name:"Name",exact:true}).fill("Website server updated");
    await dialog.getByRole("button",{name:"Save",exact:true}).click();
    await expect(dialog).not.toBeVisible();
    await page.reload();
    await expect(page.getByText("Website server updated",{exact:false})).toBeVisible();
    await page.screenshot({path:".preview/application-environment.png",fullPage:true});
    expect(errors).toEqual([]);
  });
});
