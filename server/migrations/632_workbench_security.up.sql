CREATE TABLE IF NOT EXISTS security_scans (
    id UUID NOT NULL DEFAULT gen_random_uuid(),
    workspace_id UUID NOT NULL,
    project_id UUID NOT NULL,
    repo_id UUID NOT NULL,
    issue_id UUID NOT NULL,
    run_id TEXT NOT NULL,
    artifact_version TEXT NOT NULL,
    source_commit TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('completed', 'failed')),
    scanned_at TIMESTAMPTZ NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor_type TEXT NOT NULL CHECK (actor_type IN ('member', 'agent')),
    actor_id UUID NOT NULL,
    report JSONB NOT NULL,
    digest TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS security_checks (
    id UUID NOT NULL DEFAULT gen_random_uuid(),
    number BIGINT GENERATED ALWAYS AS IDENTITY NOT NULL,
    workspace_id UUID NOT NULL,
    project_id UUID NOT NULL,
    repo_id UUID NOT NULL,
    issue_id UUID NOT NULL,
    fingerprint TEXT NOT NULL,
    severity TEXT NOT NULL CHECK (severity IN ('high', 'medium', 'low')),
    category TEXT NOT NULL CHECK (category IN ('secrets', 'deps', 'authz', 'injection')),
    title TEXT NOT NULL,
    cwe TEXT NOT NULL DEFAULT '',
    location TEXT NOT NULL,
    recommendation TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'unresolved' CHECK (status IN ('unresolved', 'pending_recheck', 'fixed', 'accepted')),
    artifact_version TEXT NOT NULL,
    first_scan_id UUID NOT NULL,
    last_scan_id UUID NOT NULL,
    fixed_scan_id UUID,
    fix_version TEXT NOT NULL DEFAULT '',
    fix_requested_at TIMESTAMPTZ,
    accepted_until TIMESTAMPTZ,
    acceptance_reason TEXT NOT NULL DEFAULT '',
    last_seen_at TIMESTAMPTZ NOT NULL,
    revision BIGINT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
